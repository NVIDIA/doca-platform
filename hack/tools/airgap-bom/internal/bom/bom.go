const (
	SchemaVersion = "v1alpha1"
	// Header is the header comment of the BOM written by airgap-bom generate.
	Header = "# Code generated by airgap-bom generate. DO NOT EDIT.\n" +
		"#\n" +
		"# Air-gap bill of materials (BOM) of DPF: the images and helm charts to copy into a mirror\n" +
		"# registry for an air-gapped installation, for everything the DPF operator deploys and the\n" +
		"# optional services DPF ships (the storage and VPC charts).\n" +
		"# First-party images and charts are listed by name only: their registry, tag and version are\n" +
		"# those DPF is installed from. Third-party images are listed by their full reference, as the\n" +
		"# repository and its charts set it, by tag or by digest.\n" +
		"# The image with sandbox: true is the pause image containerd on the DPU starts in every pod.\n" +
		"# containerd pulls it itself, so set the DPUFlavor field spec.containerdConfig.sandboxImage\n" +
		"# to its mirror copy.\n"
)

// Scope is a cluster that pulls an image: the DPU cluster or the host (management) cluster.
type Scope string

const (
	ScopeDPU  Scope = "dpu"
	ScopeHost Scope = "host"
)

// BOM is the air-gap bill of materials.
type BOM struct {
	SchemaVersion string `yaml:"schemaVersion"`
	// Images are pulled by some or all DPF installations; mirror them all.
	Images []Image `yaml:"images,omitempty"`
	// Services are optional DPUService charts; mirror only those deployed.
	Services []Service `yaml:"services,omitempty"`
	// Charts is every helm chart a DPF installation pulls, to copy into the mirror as well: the
	// first-party charts of the release and the chart of every service, which Services lists too.
	// A chart has no scope: only the host cluster pulls charts (helm installs the DPF charts, Argo
	// CD the DPUService charts); the DPU cluster pulls images only.
	Charts []Chart `yaml:"charts,omitempty"`
}

// Image is one container image. Exactly one of Name and Ref is set.
type Image struct {
	// Name is the name of a first-party (DPF-built) image. Its registry and tag are those DPF
	// is installed from.
	Name string `yaml:"name,omitempty"`
	// Ref is a third-party image reference: host/path:tag, host/path@digest or
	// host/path:tag@digest. The generator writes the normalised form of ParseImageRef, e.g.
	// docker.io/library/busybox:1.36 for busybox:1.36.
	Ref string `yaml:"ref,omitempty"`
	// Scope lists the clusters that pull the image.
	Scope []Scope `yaml:"scope,flow"`
	// Sandbox is true for the containerd sandbox (pause) image of the DPU, which containerd pulls
	// from its own configuration, not from a pod.
	Sandbox bool `yaml:"sandbox,omitempty"`
}

// Service is one optional DPUService chart and the images it pulls.
type Service struct {
	Chart  `yaml:",inline"`
	Images []Image `yaml:"images"`
}

// Chart identifies a helm chart. A first-party chart has only a name: its repository and version
// are those DPF is installed from, as for first-party images. A third-party chart has a repoURL, a
// name and a version.
type Chart struct {
	RepoURL string `yaml:"repoURL,omitempty"`
	Name    string `yaml:"name"`
	Version string `yaml:"version,omitempty"`
}

// String returns repoURL/name:version, or name for a first-party chart.
func (c Chart) String() string {
	if c.RepoURL == "" {
		return c.Name
	}
	return strings.TrimSuffix(c.RepoURL, "/") + "/" + c.Name + ":" + c.Version
}

// FirstParty reports whether the chart is a first-party chart, listed by name only.
func (c Chart) FirstParty() bool { return c.RepoURL == "" }

func (c Chart) key() string {
	return c.RepoURL + "\x00" + c.Name + "\x00" + c.Version
}

// sortKey orders first-party charts before third-party charts, each by name, repository and
// version.
func (c Chart) sortKey() string {
	if c.FirstParty() {
		return "0" + c.Name
	}
	return "1" + c.Name + "\x00" + c.RepoURL + "\x00" + c.Version
}

// key is the identity of an image entry: its name, or its normalised reference including the
// digest, so different digests of one repository or tag are different images.
func (i Image) key() string {
	if i.Name != "" {
		return "name:" + i.Name
	}
	if r, err := ParseImageRef(i.Ref); err == nil {
		return "ref:" + r.String()
	}
	return "ref:" + i.Ref
}

// sortKey orders first-party names before references, each alphabetically.
func (i Image) sortKey() string {
	if i.Name != "" {
		return "0" + i.Name
	}
	return "1" + i.Ref
}

// Validate checks the schema version, that every image is a name or a reference that parses, and
// that every chart has a name and either both repoURL and version or neither.
func (b *BOM) Validate() error {
	var errs []error
	if b.SchemaVersion != SchemaVersion {
		errs = append(errs, fmt.Errorf("unsupported schemaVersion %q, expected %q", b.SchemaVersion, SchemaVersion))
	}
	images := slices.Clone(b.Images)
	charts := slices.Clone(b.Charts)
	for _, svc := range b.Services {
		images = append(images, svc.Images...)
		charts = append(charts, svc.Chart)
	}
	for _, img := range images {
		if err := img.validate(); err != nil {
			errs = append(errs, err)
		}
	}
	for _, c := range charts {
		if err := c.validate(); err != nil {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

func (i Image) validate() error {
	switch {
	case i.Name == "" && i.Ref == "":
		return fmt.Errorf("image has neither name nor ref")
	case i.Name != "" && i.Ref != "":
		return fmt.Errorf("image %q has both name and ref %q", i.Name, i.Ref)
	case i.Ref != "":
		_, err := ParseImageRef(i.Ref)
		return err
	}
	return nil
}

func (c Chart) validate() error {
	switch {
	case c.Name == "":
		return fmt.Errorf("chart without name (repoURL %q, version %q)", c.RepoURL, c.Version)
	case (c.RepoURL == "") != (c.Version == ""):
		return fmt.Errorf("chart %q: set both repoURL and version, or neither for a first-party chart", c.Name)
	}
	return nil
}

// Parse parses and validates a BOM.
func Parse(data []byte) (*BOM, error) {
	b := &BOM{}
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(b); err != nil {
		return nil, fmt.Errorf("failed to parse BOM: %w", err)
	}
	if err := b.Validate(); err != nil {
		return nil, fmt.Errorf("invalid BOM: %w", err)
	}
	return b, nil
}

// Load reads and validates a BOM file.
func Load(path string) (*BOM, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	b, err := Parse(data)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return b, nil
}

// Marshal normalises the BOM and returns it as YAML, prefixed with header (e.g. Header;
// may be empty). The output is deterministic.
func (b *BOM) Marshal(header string) ([]byte, error) {
	b.Normalize()
	if err := b.Validate(); err != nil {
		return nil, err
	}
	buf := &bytes.Buffer{}
	buf.WriteString(header)
	enc := yaml.NewEncoder(buf)
	enc.SetIndent(2)
	if err := enc.Encode(b); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// WriteFile writes the BOM to path, creating its directory if needed, see Marshal.
func (b *BOM) WriteFile(path, header string) error {
	data, err := b.Marshal(header)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

// Normalize sorts and de-duplicates the BOM in place: images are merged by name or by reference
// including the digest (scopes united), see foldUnpinned; services are merged by chart (images
// united) and charts de-duplicated.
func (b *BOM) Normalize() {
	if b.SchemaVersion == "" {
		b.SchemaVersion = SchemaVersion
	}
	b.Images = normalizeImages(b.Images)
	services := mergeByKey(b.Services, func(s Service) string { return s.Chart.key() }, func(dst *Service, src Service) {
		dst.Images = slices.Concat(dst.Images, src.Images)
	})
	for i := range services {
		services[i].Images = normalizeImages(services[i].Images)
		if services[i].Images == nil {
			services[i].Images = []Image{}
		}
	}
	slices.SortFunc(services, func(a, b Service) int { return strings.Compare(a.Chart.sortKey(), b.Chart.sortKey()) })
	b.Services = services
	b.Charts = mergeByKey(b.Charts, Chart.key, func(*Chart, Chart) {})
	slices.SortFunc(b.Charts, func(a, b Chart) int { return strings.Compare(a.sortKey(), b.sortKey()) })
}

// mergeByKey merges the items with the same key into the first of them with merge, which must not
// modify the slices of src or dst in place. The result is in the order of first appearance.
func mergeByKey[T any](items []T, key func(T) string, merge func(dst *T, src T)) []T {
	var out []T
	index := map[string]int{}
	for _, item := range items {
		k := key(item)
		if i, ok := index[k]; ok {
			merge(&out[i], item)
			continue
		}
		index[k] = len(out)
		out = append(out, item)
	}
	return out
}

func normalizeImages(images []Image) []Image {
	byKey := map[string]*Image{}
	var keys []string
	for _, img := range images {
		k := img.key()
		existing, ok := byKey[k]
		if !ok {
			img.Scope = slices.Clone(img.Scope)
			byKey[k] = &img
			keys = append(keys, k)
			continue
		}
		mergeImage(existing, img)
	}
	keys = foldUnpinned(byKey, keys)
	out := make([]Image, 0, len(keys))
	for _, k := range keys {
		img := byKey[k]
		slices.Sort(img.Scope)
		img.Scope = slices.Compact(img.Scope)
		out = append(out, *img)
	}
	slices.SortFunc(out, func(a, b Image) int { return strings.Compare(a.sortKey(), b.sortKey()) })
	if len(out) == 0 {
		return nil
	}
	return out
}

// foldUnpinned merges every entry without digest (repo:tag, or repo meaning repo:latest) into the
// pinned entry of the same tag (repo:tag@digest) when there is exactly one, so the digest the
// repository pins wins over the registry's current one, and returns the remaining keys. A
// digest-only entry (repo@digest) is no target, its tag is unknown; with several pinned entries the
// meaning of the unpinned one is ambiguous, so it stays.
func foldUnpinned(byKey map[string]*Image, keys []string) []string {
	pinned := map[string][]string{}
	for _, k := range keys {
		img := byKey[k]
		if img.Name != "" {
			continue
		}
		if r, err := ParseImageRef(img.Ref); err == nil && r.Digest != "" && r.Tag != "" {
			pinned[img.tagKey()] = append(pinned[img.tagKey()], k)
		}
	}
	return slices.DeleteFunc(keys, func(k string) bool {
		img := byKey[k]
		if img.Name != "" {
			return false
		}
		r, err := ParseImageRef(img.Ref)
		if err != nil || r.Digest != "" {
			return false
		}
		targets := pinned[img.tagKey()]
		if len(targets) != 1 {
			return false
		}
		mergeImage(byKey[targets[0]], *img)
		return true
	})
}

// tagKey is the reference of an image entry without digest, with an absent tag as latest (as a
// container runtime pulls it), or empty for a first-party image or a reference that does not parse.
func (i Image) tagKey() string {
	if i.Name != "" {
		return ""
	}
	r, err := ParseImageRef(i.Ref)
	if err != nil {
		return ""
	}
	r = r.WithoutDigest()
	if r.Tag == "" {
		r.Tag = "latest"
	}
	return r.String()
}

// mergeImage merges img into existing, an entry with the same key: scopes are united, and the
// result is the sandbox image when either is.
func mergeImage(existing *Image, img Image) {
	existing.Scope = append(existing.Scope, img.Scope...)
	existing.Sandbox = existing.Sandbox || img.Sandbox
}

// Names returns the names of all first-party images of the BOM, images and services, sorted.
func (b *BOM) Names() []string {
	var names []string
	for _, img := range b.Images {
		if img.Name != "" {
			names = append(names, img.Name)
		}
	}
	for _, svc := range b.Services {
		for _, img := range svc.Images {
			if img.Name != "" {
				names = append(names, img.Name)
			}
		}
	}
	slices.Sort(names)
	return slices.Compact(names)
}

// ChartNames returns the names of the first-party charts of the BOM, sorted.
func (b *BOM) ChartNames() []string {
	var names []string
	for _, c := range b.Charts {
		if c.FirstParty() {
			names = append(names, c.Name)
		}
	}
	slices.Sort(names)
	return slices.Compact(names)
}
